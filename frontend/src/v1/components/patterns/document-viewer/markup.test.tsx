import { act, render } from "@testing-library/react";
import {
  expectNoA11yViolations,
  installIntersectionObserver,
  installResizeObserver,
} from "@v1/test";
import { beforeEach, expect, it } from "vitest";
import { VIEWER_GALLERY } from "./document-viewer.gallery";
import { samplePdf } from "./samplePdf";

/*
 * One file for every view and state that renders without a real browser, so a
 * markup or class change shows in review. Markdown rather than a `.snap`,
 * because v1 holds no `.snap` files. The PDF entries need pdf.js and a canvas:
 * the browser tests (tests/e2e/ui-v1/specs/P1-T21.spec.ts) cover them. React
 * ids follow the render count, so they are normalised.
 */
const SNAPSHOTTED = VIEWER_GALLERY.filter((entry) => !entry.browserOnly);

function normalise(html: string): string {
  return html.replaceAll(/_r_[0-9a-z]+_|«r[0-9a-z]+»|:r[0-9a-z]+:/g, "_id_");
}

beforeEach(() => {
  // Sizes never arrive: the views render at their initial, unmeasured state.
  installResizeObserver();
  installIntersectionObserver();
});

async function renderEntry(element: React.ReactElement) {
  const result = render(element);
  await act(async () => {
    await Promise.resolve();
  });
  return result;
}

it("matches the committed markup of every view and state", async () => {
  const sections: (readonly [string, string])[] = [];
  for (const { name, element } of SNAPSHOTTED) {
    const { container, unmount } = await renderEntry(element);
    sections.push([name, normalise(container.innerHTML)]);
    unmount();
  }
  const doc = [
    "# Document viewer markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});

it.each(
  SNAPSHOTTED.map((entry) => [entry.name, entry.element]),
)("passes the accessibility scan: %s", async (_name, element) => {
  const { container } = await renderEntry(element);
  await expectNoA11yViolations(container);
});

it("gives every entry a unique id, for the demo page's test ids", () => {
  const ids = VIEWER_GALLERY.map((entry) => entry.id);
  expect(new Set(ids).size).toBe(ids.length);
});

/*
 * The sample PDF is parsed by pdf.js only in the browser tests, so its
 * structure is checked here: a broken cross-reference table still opens in
 * pdf.js (it rebuilds the table) and would hide a generator bug.
 */
it("writes a PDF whose cross-reference table points at each object", () => {
  const text = new TextDecoder().decode(samplePdf({ pages: 3 }));
  const xrefAt = Number(/startxref\n(\d+)/.exec(text)?.[1]);
  expect(text.slice(xrefAt, xrefAt + 4)).toBe("xref");
  const entries = text
    .slice(xrefAt)
    .split("\n")
    .filter((line) => / 00000 n $/.test(line))
    .map((line) => Number(line.slice(0, 10)));
  // Catalog, page tree, font, then a page and its content per page.
  expect(entries).toHaveLength(3 + 3 * 2);
  entries.forEach((offset, index) => {
    expect(text.startsWith(`${index + 1} 0 obj`, offset)).toBe(true);
  });
  expect(text).toContain("/Count 3");
  expect(text.trimEnd().endsWith("%%EOF")).toBe(true);
});

it("draws a mark at its fractions of the page, measured from the top", () => {
  const text = new TextDecoder().decode(
    samplePdf({
      pages: 1,
      width: 600,
      height: 800,
      marks: () => [{ x: 0.1, y: 0.25, w: 0.5, h: 0.1, rgb: [255, 0, 0] }],
    }),
  );
  // Bottom edge in PDF space: 800 - (0.25 + 0.1) * 800 = 520.
  expect(text).toContain("1 0 0 rg\n60 520 300 80 re f");
});
