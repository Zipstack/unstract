import { act, render } from "@testing-library/react";
import { PORTAL_CONTAINER_ID } from "@v1/lib/portal";
import { expectNoA11yViolations } from "@v1/test";
import { expect, it } from "vitest";
import { MENU_GALLERY } from "./menu.gallery";

/*
 * One file for every variant and state, so a markup or class change shows in
 * review. Markdown rather than a `.snap`, because v1 holds no `.snap` files.
 * Open menus render into the portal container, so that is captured too.
 * React ids follow the render count, and Radix writes positioning styles, so
 * both are normalised.
 */
function normalise(html: string): string {
  return html
    .replaceAll(/_r_[0-9a-z]+_|«r[0-9a-z]+»|:r[0-9a-z]+:/g, "_id_")
    .replaceAll(/ style="[^"]*"/g, "");
}

async function renderEntry(element: React.ReactElement) {
  const result = render(element);
  // Let Radix's presence and positioning settle.
  await act(async () => {
    await Promise.resolve();
  });
  return result;
}

it("matches the committed markup of every variant", async () => {
  const sections: (readonly [string, string])[] = [];
  for (const { name, element } of MENU_GALLERY) {
    const { container, unmount } = await renderEntry(element);
    const inline = (container.firstChild as HTMLElement | null)?.outerHTML;
    const portal = document.getElementById(PORTAL_CONTAINER_ID)?.innerHTML;
    sections.push([
      name,
      normalise([inline ?? "", portal ?? ""].filter(Boolean).join("\n")),
    ]);
    unmount();
  }
  const doc = [
    "# Menu markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});

/*
 * A modal menu or dialog hides the page behind it with aria-hidden and adds
 * focusable focus guards at the edges of <body>. Focus is trapped in the open
 * surface, so neither is reachable, but axe's aria-hidden-focus still flags
 * them on a page scan. That rule is off here and every other rule runs, on
 * the open surface (the portal) and on the trigger alike.
 */
const MODAL_SCAN = { rules: { "aria-hidden-focus": { enabled: false } } };

it.each(
  MENU_GALLERY.map((entry) => [entry.name, entry.element]),
)("passes the accessibility scan: %s", async (_name, element) => {
  await renderEntry(element);
  await expectNoA11yViolations(document.body, MODAL_SCAN);
});
