import { act, render } from "@testing-library/react";
import { NOTIFY_KINDS, type NotifyKind, notify } from "@v1/lib/notify";
import type { ReactElement } from "react";
import { expect, it } from "vitest";
import { InlineAlert } from "./InlineAlert";
import { ProgressBar } from "./ProgressBar";
import {
  Skeleton,
  SkeletonAvatar,
  SkeletonBlock,
  SkeletonTableRows,
  SkeletonText,
} from "./Skeleton";
import { Spinner } from "./Spinner";
import { StepProgress } from "./StepProgress";
import { Toaster } from "./Toaster";

// One snapshot per variant and state, so a markup or class change shows in review.
const VARIANTS: [string, ReactElement][] = [
  ...NOTIFY_KINDS.map((kind): [string, ReactElement] => [
    `inline alert ${kind}`,
    <InlineAlert key="v" kind={kind} title="Title">
      Body
    </InlineAlert>,
  ]),
  [
    "inline alert with retry",
    <InlineAlert key="v" title="Could not load" onRetry={() => undefined}>
      The server did not answer.
    </InlineAlert>,
  ],
  ["progress bar", <ProgressBar key="v" aria-label="Upload" value={40} />],
  ["progress bar indeterminate", <ProgressBar key="v" aria-label="Upload" />],
  [
    "step progress",
    <StepProgress
      key="v"
      aria-label="Setup"
      steps={["A", "B", "C"]}
      current={1}
    />,
  ],
  [
    "skeleton",
    <Skeleton key="v" label="Loading">
      <SkeletonAvatar size="sm" />
      <SkeletonText />
      <SkeletonBlock />
      <SkeletonTableRows rows={2} columns={2} />
    </Skeleton>,
  ],
  ["spinner inline", <Spinner key="v" />],
  ["spinner button labelled", <Spinner key="v" size="button" label="Saving" />],
];

/** The markup of one toast of the given kind, as the Toaster renders it. */
function toastMarkup(kind: NotifyKind): string {
  const host = document.createElement("div");
  document.body.appendChild(host);
  const { unmount } = render(<Toaster container={host} />);
  act(() => {
    notify({
      kind,
      title: "Title",
      description: "Description",
      action: { label: "Action", onSelect: () => undefined },
    });
  });
  const html = host.querySelector("[data-slot=toast]")?.outerHTML ?? "";
  unmount();
  host.remove();
  return html;
}

/*
 * One file for every variant and state, so a markup or class change shows in
 * review. Markdown rather than a `.snap`, because v1 holds no `.snap` files.
 */
it("matches the committed markup of every variant", async () => {
  const sections = VARIANTS.map(([name, element]) => {
    const { container, unmount } = render(element);
    const html = (container.firstChild as HTMLElement).outerHTML;
    unmount();
    return [name, html] as const;
  });
  for (const kind of NOTIFY_KINDS) {
    sections.push([`toast ${kind}`, toastMarkup(kind)]);
  }
  const doc = [
    "# Feedback markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});
