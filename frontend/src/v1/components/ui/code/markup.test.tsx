import { render } from "@testing-library/react";
import { expect, it } from "vitest";
import { CODE_GALLERY } from "./code.gallery";

// React's useId values come from a counter shared by every render in the
// file, so they are replaced with a stable placeholder.
const stableIds = (html: string) => html.replace(/_r_[0-9a-z]+_/g, "_id_");

/*
 * One file for every gallery variant, so a markup or class change shows in
 * review. Markdown rather than a `.snap`, because v1 holds no `.snap` files.
 */
it("matches the committed markup of every variant", async () => {
  const sections = CODE_GALLERY.map(({ name, element }) => {
    const { container, unmount } = render(element);
    const html = stableIds((container.firstChild as HTMLElement).outerHTML);
    unmount();
    return [name, html] as const;
  });
  const doc = [
    "# Code and data markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});

it("every gallery variant passes axe", async () => {
  for (const { name, element } of CODE_GALLERY) {
    const { container, unmount } = render(element);
    await expect(container, name).toHaveNoA11yViolations();
    unmount();
  }
});
