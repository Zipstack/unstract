import { render } from "@testing-library/react";
import type { ReactElement } from "react";
import { expect, it } from "vitest";
import {
  AreaChart,
  BarChart,
  LineChart,
  numberFormats,
  Sparkline,
  StackedBarChart,
} from "./index";

// A fixed locale, so the snapshot holds on any machine.
const EN = numberFormats("en-US");
const data = [
  { day: "9 Aug", pages: 10, failed: 1 },
  { day: "10 Aug", pages: 2981, failed: 600 },
  { day: "11 Aug", pages: 20, failed: 2 },
];
const series = [
  { key: "pages", label: "Pages processed", tone: "primary" },
  { key: "failed", label: "Failed pages", tone: "destructive" },
] as const;
const ramp = [
  { key: "failed", label: "Failed" },
  { key: "pages", label: "Pages" },
] as const;
const shared = {
  title: "Throughput",
  data,
  xKey: "day",
  width: 320,
  height: 160,
  valueFormat: EN.value,
} as const;
const axes = { axisFormat: EN.axis } as const;
const marker = [{ index: 1, series: "pages", label: "Peak" }] as const;

// One snapshot per variant and state, so a markup or class change shows in review.
const VARIANTS: [string, ReactElement][] = [
  [
    "line",
    <LineChart
      key="v"
      {...shared}
      {...axes}
      series={series}
      markers={marker}
    />,
  ],
  ["area", <AreaChart key="v" {...shared} {...axes} series={ramp} />],
  [
    "bar",
    <BarChart key="v" {...shared} {...axes} series={ramp} legend="top" />,
  ],
  [
    "stacked bar",
    <StackedBarChart
      key="v"
      {...shared}
      {...axes}
      series={ramp}
      markers={marker}
    />,
  ],
  ["sparkline", <Sparkline key="v" {...shared} series={[series[0]]} />],
  [
    "loading",
    <LineChart key="v" {...shared} {...axes} series={series} state="loading" />,
  ],
  [
    "empty",
    <BarChart
      key="v"
      {...shared}
      {...axes}
      series={ramp}
      data={[] as typeof data}
    />,
  ],
];

/** useId and Recharts' generated clip-path ids change with render order; pin them. */
function normalise(html: string): string {
  const ids = new Map<string, string>();
  return html.replace(
    /(_r_[0-9a-z]+_|recharts\d*-clip(?:-path)?[-\w]*)/g,
    (id) => {
      const known = ids.get(id);
      if (known !== undefined) {
        return known;
      }
      const next = `id-${ids.size + 1}`;
      ids.set(id, next);
      return next;
    },
  );
}

it("matches the committed markup of every variant", async () => {
  const sections = VARIANTS.map(([name, element]) => {
    const { container, unmount } = render(element);
    const html = normalise((container.firstChild as HTMLElement).outerHTML);
    unmount();
    return [name, html] as const;
  });
  const doc = [
    "# Chart markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});
