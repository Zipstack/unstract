import { render } from "@testing-library/react";
import { expectNoA11yViolations, renderV1 } from "@v1/test";
import { describe, expect, it, vi } from "vitest";
import { DATA_TABLE_GALLERY } from "./data-table.gallery";

/*
 * One file for every variant and state, so a markup or class change shows in
 * review. Markdown rather than a `.snap`, because v1 holds no `.snap` files.
 * React ids (`_r_0_`) follow the render count, so they are normalised.
 * happy-dom's window is 1024 wide, so priority 3 and 4 columns are dropped.
 * happy-dom lays nothing out, so every box is given a 560-tall client area:
 * the virtualised 1,000-row table then renders the rows a real 560px
 * viewport would, plus overscan.
 */
function stubViewport(): void {
  vi.spyOn(HTMLElement.prototype, "clientHeight", "get").mockReturnValue(560);
}
function normalise(html: string): string {
  return html.replaceAll(/_r_[0-9a-z]+_|«r[0-9a-z]+»|:r[0-9a-z]+:/g, "_id_");
}

it("matches the committed markup of every variant", async () => {
  stubViewport();
  const sections = DATA_TABLE_GALLERY.map(({ name, element }) => {
    const { container, unmount } = render(element);
    const html = normalise((container.firstChild as HTMLElement).outerHTML);
    unmount();
    return [name, html] as const;
  });
  const doc = [
    "# Data table markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});

it("passes the accessibility scan with every entry on one page, as the gallery shows them", async () => {
  stubViewport();
  const { container } = renderV1(
    <div>
      {DATA_TABLE_GALLERY.map(({ name, element }) => (
        <section key={name} aria-label={name}>
          {element}
        </section>
      ))}
    </div>,
  );
  await expectNoA11yViolations(container);
});

describe.each([
  "light",
  "dark",
  "unstract",
] as const)("gallery in %s", (theme) => {
  it.each(
    DATA_TABLE_GALLERY.map((entry) => [entry.name, entry.element]),
  )("passes the accessibility scan: %s", async (_name, element) => {
    stubViewport();
    const { container } = renderV1(element, { theme });
    expect(document.querySelector(`[data-theme="${theme}"]`)).not.toBeNull();
    await expectNoA11yViolations(container);
  });
});
