import { render } from "@testing-library/react";
import { expectNoA11yViolations } from "@v1/test";
import { expect, it } from "vitest";
import { NAVIGATION_GALLERY } from "./navigation.gallery";

/*
 * One file for every variant and state, so a markup or class change shows in
 * review. Markdown rather than a `.snap`, because v1 holds no `.snap` files.
 * React ids (`_r_0_`) follow the render count, so they are normalised.
 */
function normalise(html: string): string {
  return html.replaceAll(/_r_[0-9a-z]+_|«r[0-9a-z]+»|:r[0-9a-z]+:/g, "_id_");
}

it("matches the committed markup of every variant", async () => {
  const sections = NAVIGATION_GALLERY.map(({ name, element }) => {
    const { container, unmount } = render(element);
    const html = normalise((container.firstChild as HTMLElement).outerHTML);
    unmount();
    return [name, html] as const;
  });
  const doc = [
    "# Navigation markup",
    "",
    "Generated by `markup.test.tsx`; update with `vitest -u`.",
    ...sections.flatMap(([name, html]) => [
      "",
      `## ${name}`,
      "",
      "```html",
      html.replaceAll("><", ">\n<"),
      "```",
    ]),
    "",
  ].join("\n");
  await expect(doc).toMatchFileSnapshot("./__snapshots__/markup.md");
});

it.each(
  NAVIGATION_GALLERY.map((entry) => [entry.name, entry.element]),
)("passes the accessibility scan: %s", async (_name, element) => {
  const { container } = render(element);
  await expectNoA11yViolations(container);
});
