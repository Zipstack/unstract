import { expect, it } from "vitest";
import {
  renderTokensCss,
  renderTokenTable,
  sameInEveryMode,
  type Token,
} from "./tokens";

const radius: Token = {
  family: "radius",
  name: "radius-sm",
  cssVar: "--radius-sm",
  utility: "v1:rounded-sm",
  values: sameInEveryMode("6px"),
};
const bg: Token = {
  family: "colour",
  name: "background",
  cssVar: "--background",
  utility: "v1:bg-background",
  values: { light: "#fafafa", dark: "#1a1a1a", unstract: "#0f0a1f" },
};

it("renders one scoped block per mode with every token in each", () => {
  expect(renderTokensCss([bg, radius])).toBe(
    "/* Generated by scripts/build-v1-tokens.mjs from src/v1/styles/tokens.ts. Do not edit. */\n" +
      '.v1[data-theme="light"] {\n  --background: #fafafa;\n  --radius-sm: 6px;\n}\n' +
      '.v1[data-theme="dark"] {\n  --background: #1a1a1a;\n  --radius-sm: 6px;\n}\n' +
      '.v1[data-theme="unstract"] {\n  --background: #0f0a1f;\n  --radius-sm: 6px;\n}\n',
  );
});

it("renders the gallery table with one row per token", () => {
  const table = renderTokenTable([bg]);
  expect(table.split("\n")[0]).toBe(
    "| Family | Token | CSS variable | Utility | Light | Dark | Unstract |",
  );
  expect(table).toContain(
    "| colour | background | `--background` | `v1:bg-background` | #fafafa | #1a1a1a | #0f0a1f |",
  );
});
